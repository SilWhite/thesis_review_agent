const fs = require('fs'), vm = require('vm'), assert = require('assert');
const context={window:{}}; vm.createContext(context);vm.runInContext(fs.readFileSync('app/static/evidence.js','utf8'),context);
const ui=context.window.ReviewEvidence;
assert.equal(ui.highlight('A <script>bad</script> A',['A']),'<mark>A</mark> &lt;script&gt;bad&lt;/script&gt; <mark>A</mark>');
assert.equal(ui.highlight('前文 Transformer 的分层特征 后文',['Transformer的分层特征']),'前文 <mark>Transformer 的分层特征</mark> 后文');
const html=ui.render({filename:'paper.pdf',issue:'test',measurement:'空白 60%',evidence_note:'核对位置',locations:[{page:5,quote:'第一处',context:'上下文第一处',bbox:[1,2,3,4]},{page:7,quote:'第二处'}]}, {}, 'job_test',3);
assert(html.includes('PDF 第 5 页')&&html.includes('PDF 第 7 页')&&html.includes('空白 60%')&&html.includes('/evidence/3/1'));
const fallback=ui.render({block_id:'other',quote:'关键证据'}, {other:{text:'无关整页'}},'job',0);
assert(fallback.includes('关键证据')&&!fallback.includes('无关整页'));
console.log('Evidence UI escaping, multiple locations and unrelated-source rejection passed');
