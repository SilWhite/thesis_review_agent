const fs = require('fs'), assert = require('assert');
const workspace = require('../fixtures/workspace_ui.cjs');
(async () => {
    const {el, calls, run} = await workspace();
    el('#files').files = [{name: 'paper.pdf'}];
    el('#prompt').value = '重点查看实验数据划分';
    await el('#review-form').onsubmit({preventDefault() {}});
    const submit = calls.find(c => c.url === '/api/v1/jobs' && c.options.method);
    assert(submit && submit.body.custom_prompt === '重点查看实验数据划分' && submit.body.model_mode === 'local');
    assert(!calls.some(c => c.url.includes('/documents/text') || c.url === '/api/v1/audits'));
    calls.length = 0; el('#files').files = [];
    await el('#review-form').onsubmit({preventDefault() {}});
    assert.equal(calls.length, 0); assert(el('#toast').textContent.includes('上传论文'));
    run('globalThis.state={jobId:"one",digest:"hash",excluded:new Set([0]),queue:Promise.resolve(),pending:0}');
    const first = run('saveReviewSelection(state)'); run('state.excluded.add(1)');
    const second = run('saveReviewSelection(state)'); await Promise.all([first, second]);
    const writes = calls.filter(c => c.url.endsWith('/review-decisions'));
    assert.deepEqual(writes.map(c => c.body.excluded_findings), [[0], [0, 1]]);
    assert.deepEqual(writes.map(c => c.body.revision), [0, 1]);
    const html = fs.readFileSync('app/static/index.html', 'utf8');
    assert(html.includes('id="prompt" rows="6"') && !html.includes('value="mock"') && !html.includes('id="text"'));
    assert(!/DEMO|本地演示版|填入测试材料/.test(html));
    assert(html.indexOf('/static/review.js') < html.indexOf('/static/app.js'));
    console.log('Original review request, required material, focus and serialized decisions preserved');
})().catch(e => {console.error(e); process.exitCode = 1;});
