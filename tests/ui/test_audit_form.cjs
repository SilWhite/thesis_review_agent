const assert = require('assert'), workspace = require('../fixtures/workspace_ui.cjs');
(async () => {
    const {el, calls, run} = await workspace();
    el('#check-review').checked = false; el('#check-novelty').checked = true;
    el('#paper-existing').value = 'doc_one'; el('#audit-queries').value = 'public topic';
    await el('#review-form').onsubmit({preventDefault() {}});
    assert.equal(calls.length, 0); assert(el('#toast').textContent.includes('批准'));
    el('#audit-approved').checked = true;
    await el('#review-form').onsubmit({preventDefault() {}});
    const body = calls.find(c => c.url === '/api/v1/audits').body;
    assert.deepEqual(body.public_queries, ['public topic']); assert(body.search_approved);
    assert.equal(body.model_mode, 'local'); assert.deepEqual(body.experiments, []);
    assert.equal(body.document_id, 'doc_one');
    assert(!calls.some(c => c.options.method && ['/api/v1/jobs', '/api/v1/documents', '/api/v1/search'].includes(c.url)));
    el('#audit-queries').oninput(); assert(!el('#audit-approved').checked);
    calls.length = 0; el('#material-file').files = [{name: 'train.csv'}];
    el('#material-role').value = 'data'; el('#material-split').value = 'train'; el('#material-id-column').value = 'id';
    await el('#add-material').onclick();
    const fields = calls[0].body.fields;
    assert.equal(fields.role, 'data'); assert.equal(fields.split, 'train'); assert.equal(fields.id_column, 'id');
    el('#check-novelty').checked = false; el('#check-experiments').checked = true;
    el('#experiment-quote').value = '训练集共3条。'; calls.length = 0;
    await el('#review-form').onsubmit({preventDefault() {}});
    const experimental = calls.find(c => c.url === '/api/v1/audits').body;
    assert.deepEqual(experimental.experiments[0].material_ids, ['mat_test']);
    assert.deepEqual(experimental.public_queries, []); assert(!experimental.search_approved);
    assert(!calls.some(c => c.url === '/api/v1/audit-materials'));
    const html = run('noveltyHtml({status:"信息不足",basis:"<script>bad</script>",sources:[],comparisons:[],notes:[]})');
    assert(html.includes('&lt;script&gt;') && !html.includes('<script>'));
    el('#repository-location').value = '/srv/repos/example';
    el('#experiment-quote').value = '';
    calls.length = 0;
    await el('#review-form').onsubmit({preventDefault() {}});
    const repository = calls.find(c => c.url === '/api/v1/audits').body;
    assert.equal(repository.repository.location, '/srv/repos/example');
    assert.deepEqual(repository.experiments, []);
    assert.equal(repository.repository.kind, 'local');
    assert.equal(repository.repository.ref, null);
    el('#repository-location').value = 'https://github.com/owner/repo';
    calls.length = 0;
    await el('#review-form').onsubmit({preventDefault() {}});
    assert.equal(calls.find(c => c.url === '/api/v1/audits').body.repository.kind, 'github');
    const pageHtml = require('fs').readFileSync('app/static/index.html', 'utf8');
    assert(!pageHtml.includes('repository-kind') && !pageHtml.includes('repository-ref'));
    assert(pageHtml.includes('<details id="legacy-experiment">'));
    assert(!repository.check_novelty && !repository.check_citations);
    console.log('Optional audit: material reuse, repository mode without manual excerpt or literature network, escaped output');
})().catch(e => {console.error(e); process.exitCode = 1;});
